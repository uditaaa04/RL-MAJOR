"""
Turn real (or mock) run logs into the same tables + graphs as the simulator.

    python -m tools.report_real                 # all runs in logs/
    python -m tools.report_real --prefix exp1122_1430

Writes results/REAL_RESULTS.md and results/figures/REAL_*.png
"""
from __future__ import annotations

import argparse
import glob
import os

import numpy as np
import pandas as pd

from common.algos import rolling_mean
from common.config import project_path


def load_runs(prefix: str | None):
    runs = []
    for d in sorted(glob.glob(project_path("logs/*"))):
        name = os.path.basename(d)
        if prefix and not name.startswith(prefix):
            continue
        f = os.path.join(d, "boxes.csv")
        if os.path.exists(f) and os.path.getsize(f) > 0:
            df = pd.read_csv(f)
            if len(df):
                df["run"] = name
                runs.append(df)
    return runs


def metrics(df: pd.DataFrame) -> dict:
    n = len(df)
    known = df[df["truth"].isin(["good", "damaged"])] if "truth" in df else df.iloc[0:0]
    dam = known[known["truth"] == "damaged"]
    return {
        "boxes": n,
        "ESP32 %": 100 * (df["action"] == "EDGE").mean(),
        "gateway %": 100 * (df["action"] == "GATEWAY").mean(),
        "cloud %": 100 * (df["action"] == "CLOUD").mean(),
        "missed %": 100 * (1 - df["on_time"].mean()),
        "accuracy %": 100 * (known["verdict"] == known["truth"]).mean() if len(known) else np.nan,
        "damaged got through %": 100 * (dam["verdict"] != "damaged").mean() if len(dam) else np.nan,
        "mean latency ms": df.loc[df["on_time"] == 1, "latency_ms"].mean(),
        "reward / box": df["reward"].mean(),
        "energy mJ / box": df["energy_mJ"].mean(),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prefix", default=None)
    a = ap.parse_args()
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    runs = load_runs(a.prefix)
    if not runs:
        raise SystemExit("no logs found in logs/ (run gateway_node.main or tools.run_experiment first)")
    os.makedirs(project_path("results/figures"), exist_ok=True)
    L = ["# Real-hardware results (auto-generated by `python -m tools.report_real`)\n"]

    name = lambda r: r["run"].iloc[0]
    steady = [r for r in runs if "_steady_" in name(r)]
    change = [r for r in runs if "_change-" in name(r)]
    other = [r for r in runs if "_steady_" not in name(r) and "_change-" not in name(r)]

    if steady:
        rows = []
        for r in steady:
            run_name = r["run"].iloc[0]
            pol, sc = run_name.split("_steady_")[1].rsplit("_", 1)
            rows.append({"scenario": sc, "policy": pol, **metrics(r)})
        t = pd.DataFrame(rows).sort_values(["scenario", "policy"])
        L.append("## Steady conditions\n")
        L.append(t.to_markdown(index=False, floatfmt=".2f"))
        fig, axes = plt.subplots(1, 2, figsize=(12, 4))
        for ax, col in zip(axes, ["reward / box", "missed %"]):
            pv = t.pivot(index="scenario", columns="policy", values=col)
            pv.plot.bar(ax=ax, rot=0)
            ax.set_title(col); ax.grid(axis="y", alpha=0.3)
        fig.tight_layout(); fig.savefig(project_path("results/figures/REAL_steady.png"), dpi=150); plt.close(fig)
        L.append("\n![](figures/REAL_steady.png)\n")

    if change:
        L.append("## Change in the middle\n")
        by_change = {}
        for r in change:
            ch, pol = r["run"].iloc[0].split("_change-")[1].split("_", 1)
            by_change.setdefault(ch, []).append((pol, r))
        for ch, lst in by_change.items():
            fig, ax = plt.subplots(figsize=(9, 3.6))
            rows = []
            for pol, r in lst:
                miss = 1 - r["on_time"].to_numpy()
                w = 15
                roll = rolling_mean(miss, w) * 100          # prefix sums, O(n)
                ax.plot(np.arange(w - 1, w - 1 + len(roll)), roll, label=pol)
                third = len(r) // 3
                rows.append({"policy": pol, "missed % before": 100 * miss[:third].mean(),
                             "missed % during": 100 * miss[third:2 * third].mean(),
                             "missed % after": 100 * miss[2 * third:].mean(), "reward / box": r["reward"].mean()})
            n = max(len(r) for _, r in lst)
            ax.axvspan(n / 3, 2 * n / 3, color="#fee2e2", alpha=0.6, lw=0)
            ax.set_title(f"good -> {ch} -> good (red band = problem)", loc="left")
            ax.set_xlabel("box"); ax.set_ylabel("missed %, rolling 15"); ax.legend(fontsize=8); ax.grid(alpha=0.3)
            fig.tight_layout(); fig.savefig(project_path(f"results/figures/REAL_change_{ch}.png"), dpi=150); plt.close(fig)
            L.append(f"### {ch}\n")
            L.append(pd.DataFrame(rows).to_markdown(index=False, floatfmt=".2f"))
            L.append(f"\n![](figures/REAL_change_{ch}.png)\n")

    if other:
        L.append("## Other runs\n")
        L.append(pd.DataFrame([{"run": r["run"].iloc[0], **metrics(r)} for r in other]).to_markdown(index=False, floatfmt=".2f"))

    with open(project_path("results/REAL_RESULTS.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))
    print("\nsaved results/REAL_RESULTS.md")


if __name__ == "__main__":
    main()
